def test_execution_lease_blocks_revision_and_another_writer(scenario):
    orders, thread, problem, plan, _, channel = scenario
    a, b = orders.prepare(OWNER, thread, plan)
    approve(orders, thread, a)
    approve(orders, thread, b)

    async def observed(**kwargs):
        with pytest.raises(ApprovalError) as failure:
            orders.revise(OWNER, thread, revise_problem(problem, budget="2600.00").problem)
        assert failure.value.code == "REVISION_CONFLICT"
        with pytest.raises(ApprovalError) as failure:
            await orders.execute(OWNER, thread, b.interrupt_id, channel=channel)
        assert failure.value.code == "EXECUTION_BUSY"
        return await channel(**kwargs)

    assert execute(orders, thread, a, observed)["ok"]


def test_lost_response_keeps_lease_and_retry_uses_same_erp_operation(scenario, db):
    orders, thread, problem, plan, erp, channel = scenario
    a = orders.prepare(OWNER, thread, plan)[0]
    approve(orders, thread, a)
    before = actual_orders(erp)["total"]

    async def response_lost(**kwargs):
        await channel(**kwargs)  # the real ERP has committed; client loses its response
        raise TimeoutError("injected loss after real write")

    with pytest.raises(TimeoutError):
        execute(orders, thread, a, response_lost)
    assert actual_orders(erp)["total"] == before + 1
    assert orders.load(OWNER, thread, thread)["execution"]["phase"] == "uncertain"
    with pytest.raises(ApprovalError):
        orders.revise(OWNER, thread, revise_problem(problem, budget="2600.00").problem)
    restarted = PlanningOrders(db, grant_secret=SECRET)
    result = execute(restarted, thread, a, channel)
    assert result["ok"]
    assert actual_orders(erp)["total"] == before + 1
    assert restarted.load(OWNER, thread, thread)["orders"][0]["operation_id"] == a.operation_id


