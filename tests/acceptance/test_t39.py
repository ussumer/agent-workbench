def test_signed_old_grant_is_rejected_at_real_gateway_after_revision(scenario, stack):
    orders, thread, problem, plan, erp, channel = scenario
    a = orders.prepare(OWNER, thread, plan)[0]
    approve(orders, thread, a)
    captured = {}

    async def capture(**kwargs):
        captured.update(kwargs)
        verified = orders.approvals.verify_internal(
            owner_user_id=OWNER, thread_id=thread, interrupt_id=a.interrupt_id,
            tool_name=a.tool_name, target=a.target, payload_sha256=a.payload_sha256,
            operation_id=a.operation_id,
        )
        assert verified.status == PendingStatus.EXECUTING
        # Definitive refusal lets the lease end, while the signed grant is retained.
        return {"ok": False, "error": {"code": "INVALID_ARGUMENT", "retryable": False}}

    execute(orders, thread, a, capture)
    orders.revise(OWNER, thread, revise_problem(problem, budget="2600.00").problem)
    with httpx.Client(trust_env=False, timeout=5) as client:
        check = client.post(stack[2], headers={"x-internal-service-token": INTERNAL}, json={
            "owner_user_id": OWNER, "thread_id": thread, "interrupt_id": a.interrupt_id,
            "tool_name": a.tool_name, "target": a.target, "payload_sha256": a.payload_sha256,
            "operation_id": a.operation_id,
        })
    assert check.status_code == 409
    assert check.json()["error"]["code"] == "STALE_PLAN"
    before = actual_orders(erp)["total"]
    result = asyncio.run(channel(**captured))
    if isinstance(result, list):
        result = json.loads(next(b["text"] for b in result if "text" in b))
    elif isinstance(result, str):
        result = json.loads(result)
    assert result["ok"] is False, result
    assert result["error"]["code"] == "APPROVAL_REQUIRED"
    assert actual_orders(erp)["total"] == before


