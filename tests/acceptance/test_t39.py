def test_two_concurrent_approvals_have_one_winner(scenario):
    orders, thread, _, plan, _, _ = scenario
    a = orders.prepare(OWNER, thread, plan)[0]

    def decide(_):
        try:
            return approve(orders, thread, a).status
        except ApprovalError as failure:
            return failure.code

    with ThreadPoolExecutor(max_workers=2) as pool:
        results = list(pool.map(decide, range(2)))
    assert results.count(PendingStatus.APPROVED) == 1
    assert results.count("ALREADY_DECIDED") == 1


