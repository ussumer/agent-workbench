def approve(orders, thread, action):
    return orders.approvals.approve(owner_user_id=OWNER, thread_id=thread,
                                   interrupt_id=action.interrupt_id, request_id=uuid.uuid4().hex)


def actual_orders(erp):
    with erp.client() as client:
        response = client.get("/api/erp/v1/orders", params={"page": 1, "page_size": 100})
        response.raise_for_status()
        return response.json()["data"]


def execute(orders, thread, action, channel):
    return asyncio.run(orders.execute(OWNER, thread, action.interrupt_id, channel=channel))


def test_two_orders_are_reviewed_individually_and_written_exactly_once(scenario):
    orders, thread, _, plan, erp, channel = scenario
    before = actual_orders(erp)["total"]
    actions = orders.prepare(OWNER, thread, plan)
    assert len(actions) == 2
    assert actual_orders(erp)["total"] == before
    results = []
    for i, action in enumerate(actions):
        approve(orders, thread, action)
        result = execute(orders, thread, action, channel)
        assert result["ok"], result
        assert actual_orders(erp)["total"] == before + i + 1
        assert execute(orders, thread, action, channel) == result
        results.append(result)
    written = {r["data"]["order_id"] for r in results}
    rows = [r for r in actual_orders(erp)["items"] if r["order_id"] in written]
    assert len(rows) == 2
    for action in actions:
        row = next(r for r in rows if r["supplier_id"] == action.payload["supplier_id"])
        assert row["note"] == action.payload["note"]
        assert sorted((r["part_id"], r["quantity"], r["unit_price"]) for r in row["lines"]) == sorted(
            (r["part_id"], r["quantity"], r["unit_price"]) for r in action.payload["lines"])
    assert actual_orders(erp)["total"] == before + 2
    assert len(orders.load(OWNER, thread, thread)["orders"]) == 2


